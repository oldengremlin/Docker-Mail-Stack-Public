#!/bin/bash
# ─────────────────────────────────────────────────────────────────────
#  Entrypoint образу spamassassin.
#
#  Два процеси: `spamd` (сканер) і `spamass-milter` (адаптер до
#  Postfix). В одному контейнері свідомо — мілтер без spamd не має
#  сенсу й масштабується разом із ним, це адаптер, а не самостійний
#  сервіс. Нагляд нижче: помер будь-який — виходимо, Docker підіймає.
#
#  bash, а не sh, рівно через `wait -n` у наглядачі: у POSIX sh немає
#  способу дочекатись ПЕРШОГО, хто завершився. Решта entrypoint-ів у
#  проєкті лишаються на sh.
# ─────────────────────────────────────────────────────────────────────
set -eu

SHARED=/etc/spamassassin/shared
CUSTOM=/etc/spamassassin/config
LOCAL_CF=/etc/spamassassin/local.cf
SQL_CF=/etc/spamassassin/sql.cf

die() { echo "spamassassin-entrypoint: $*" >&2; exit 1; }
say() { echo "spamassassin-entrypoint: $*" >&2; }

# ── Логи мілтера ──────────────────────────────────────────────────────
# `spamd` уміє писати в stderr сам (`--syslog=stderr`), а
# `spamass-milter` — ні: він sendmail-мілтер і пише лише в syslog.
# Конструкція та сама, що в opendkim/opendmarc; `fork` і `echo >&2` там
# не косметика — syslog-датаграми не містять переносу рядка, а
# журнальний драйвер Docker ріже потік саме по ньому й тримає
# незакінчений рядок у буфері. Повний розбір — в entrypoint opendkim.
syslog_to_stderr() {
    rm -f /dev/log
    socat -u UNIX-RECVFROM:/dev/log,mode=0666,fork \
          SYSTEM:'cat >&2; echo >&2' &
    i=0
    while [ ! -S /dev/log ] && [ "$i" -lt 50 ]; do i=$((i + 1)); sleep 0.1; done
    [ -S /dev/log ] || say "УВАГА — не вдалось підняти злив /dev/log у stderr, логів мілтера не буде"
}

# ── Конфіг: груповий перекриває спільний ──────────────────────────────
if [ -f "$CUSTOM/local.cf" ]; then
    SRC=$CUSTOM/local.cf
    say "конфіг ГРУПИ $SRC (перекриває спільний)"
elif [ -f "$SHARED/local.cf" ]; then
    SRC=$SHARED/local.cf
else
    die "немає ні $CUSTOM/local.cf, ні $SHARED/local.cf — перевір
GROUP_CONFIG_DIR у group.env і те, що _configs/ на місці"
fi
cp "$SRC" "$LOCAL_CF"

# ── Обов'язкові змінні ────────────────────────────────────────────────
# Усі разом і з повним списком: інакше запуск перетворюється на
# «виправив одну, дізнався про наступну».
missing=
for v in MYSQL_HOST SA_DB SA_DB_USER SA_DB_PASSWORD POSTMASTER_ADDRESS INTERNAL_PREFIX; do
    eval "val=\${$v:-}"
    [ -n "$val" ] || missing="$missing $v"
done
[ -z "$missing" ] || die "не задані змінні:$missing"

# MYNETWORKS тут НЕ обов'язковий, і це не послаблення перевірки.
# Рішення №30: довіра до мережі — окремий параметр від того, які адреси
# група має, і групі цілком дозволено не довіряти НІКОМУ (small має
# офісну мережу, але не довіряє їй). Порожнє значення означає «жодного
# -i», тобто сканувати всіх, крім автентикованих.
MYNETWORKS=${MYNETWORKS:-}

# ── Підключення до БД (рішення №33) ───────────────────────────────────
# Окремим файлом, а не в local.cf, бо тут пароль: local.cf приходить із
# репозиторію, а цей файл складається тут і нікуди не їде.
#
# Чому окрема база, а не поштова: інакше цей контейнер отримав би
# доступ до `usersdb`, тобто до хешів паролів усіх користувачів групи.
# Сканеру вмісту там нічого робити.
case "$SA_DB_PASSWORD" in
    *$'\n'*) die "SA_DB_PASSWORD містить перенос рядка — конфіг SpamAssassin такого не переживе" ;;
esac

# DNSBL: у group.env позитивне SA_DNSBL=yes|no, у конфізі — інвертоване
# skip_rbl_checks. Дефолт `yes` збігається з дефолтом SpamAssassin.
case "${SA_DNSBL:-yes}" in
    yes|true|1)  SA_SKIP_RBL=0 ;;
    no|false|0)  SA_SKIP_RBL=1
                 say "DNSBL ВИКЛЮЧЕНІ (SA_DNSBL=${SA_DNSBL})" ;;
    *) die "SA_DNSBL='${SA_DNSBL}' — умію yes і no" ;;
esac

umask 077
# ┌───────────────────────────────────────────────────────────────────┐
# │ УВАГА: розділювач heredoc тут НЕ в лапках — так і має бути, бо    │
# │ всередині підставляються змінні. Наслідок: БЕКТИКИ І $(...) У     │
# │ ЦЬОМУ БЛОЦІ ВИКОНУЮТЬСЯ, навіть у рядках, які виглядають          │
# │ коментарями — для shell вони просто текст heredoc.                │
# │                                                                   │
# │ Уже спіймались: `awl` у коментарі перетворилось на спробу         │
# │ виконати команду awl, і в згенерованому файлі лишилась дірка на   │
# │ місці слова. Тож ніяких бектиків нижче — «лапки» або просто       │
# │ слово.                                                            │
# └───────────────────────────────────────────────────────────────────┘
cat > "$SQL_CF" <<EOF
# ЗГЕНЕРОВАНО entrypoint-ом. Правити тут немає сенсу — перезапишеться.
# Джерело значень — environment сервісу spamassassin у шаблоні compose.

# Bayes у SQL, а не у файлах: том зі станом тоді не потрібен, а дані
# переносяться з прода разом з іншими таблицями.
# ── DNS-блоклисти ─────────────────────────────────────────────────────
# Параметр ГРУПИ (SA_DNSBL), а не зашите значення: користь від DNSBL
# повністю залежить від того, ЧИЙ резолвер бачить контейнер. Зі своїм
# рекурсивним вони працюють як задумано; через публічний (8.8.8.8 і
# подібні) Spamhaus відповідає відмовою, яка виглядає як «занесено» —
# тобто правило спрацьовує на все. Деталі — у спільному local.cf.
#
# skip_rbl_checks інвертований щодо SA_DNSBL навмисно: у group.env
# стоїть те, чого людина хоче («DNSBL вмикаю»), а не те, що треба
# вимкнути, щоб це сталось.
skip_rbl_checks         ${SA_SKIP_RBL}

bayes_store_module      Mail::SpamAssassin::BayesStore::MySQL
bayes_sql_dsn           DBI:mysql:${SA_DB}:${MYSQL_HOST}
bayes_sql_username      ${SA_DB_USER}
bayes_sql_password      ${SA_DB_PASSWORD}

# Per-user налаштування. Сюди ж належить whitelist_from_rcvd
# (рішення №18): це директива SpamAssassin, а не мапа Postfix, тож
# postmap до неї не стосується. Глобальні правила — рядком для
# псевдокористувача \$GLOBAL.
user_scores_dsn         DBI:mysql:${SA_DB}:${MYSQL_HOST}
user_scores_sql_username ${SA_DB_USER}
user_scores_sql_password ${SA_DB_PASSWORD}

# AWL (auto-whitelist) ТУТ СВІДОМО НЕМАЄ, хоч на office таблиця awl
# є і налаштована. Три причини, і перша технічна:
#
#   1. У SpamAssassin 4 плагін AWL оголошений застарілим і НЕ
#      завантажується за замовчуванням (у v310.pre закомментований).
#      Директиви auto_whitelist_factory і user_awl_* через це просто
#      невідомі парсеру — spamassassin --lint дає issues і ненульовий код.
#      Увімкнути можна, але це означало б свідомо спиратись на те, що
#      апстрім уже оголосив тупиком.
#   2. AWL — ще один механізм із пам'яттю, тобто зворотний зв'язок. Ми
#      щойно прибрали інший такий (навчання на sieve-копіях у .Junk) за
#      те, що він сам себе переконував у помилці. AWL менш небезпечний
#      (усереднює, а не вчить), але клас той самий.
#   3. Переносити дані AWL із прода сенсу мало: це репутаційні середні,
#      вони відновляться самі за кілька тижнів роботи.
#
# Заміна в апстрімі — TxRep, і txrep_mysql.sql у пакеті Є. Але
# вмикати його зараз рано: рішення №21 вимагає спершу статистики на
# маркуванні, а TxRep агресивніший за AWL. Записано в TODO п.5.
EOF
chmod 640 "$SQL_CF"
chgrp debian-spamd "$SQL_CF" 2>/dev/null || true
umask 022

# ── Режим перевірки ───────────────────────────────────────────────────
# `docker run --rm ... mail/spamassassin:trixie check` друкює розбір
# конфігу й виходить. Потрібен із тієї ж причини, що в dovecot і
# postfix: зламаний конфіг кладе контейнер у restart-loop, і
# `docker exec` у нього вже не зайти.
case "${1:-}" in
    '')      ;;
    check)
        # --lint при успіху МОВЧИТЬ, а команда зветься `config` і людина
        # прийшла дивитись конфіг. Тому друкуємо ще й те, що склалось:
        # який файл узято і що пішло в sql.cf.
        #
        # ┌───────────────────────────────────────────────────────────┐
        # │ МАСКУЄМО ПАРОЛІ У ВСЬОМУ ВИВОДІ, не лише в sql.cf.        │
        # │                                                           │
        # │ `spamassassin --lint` при помилці розбору друкує ПРОБЛЕМНИЙ│
        # │ РЯДОК ЦІЛКОМ — разом зі значенням. Один раз це вже        │
        # │ сталось: пароль до БД виїхав у термінал і далі в чат.     │
        # │                                                           │
        # │ Вивід цієї команди за призначенням іде людям — у тикети,  │
        # │ у листи, в чати. Тож фільтр ставимо на ВСЕ, а не на той   │
        # │ файл, про який ми зараз думаємо.                          │
        # └───────────────────────────────────────────────────────────┘
        mask() { sed -E 's/((pass(word)?|secret|token)[[:space:]=:]+).*/\1<замасковано>/I'; }

        {
            echo "── взято конфіг: $SRC ──"
            cat "$LOCAL_CF"
            echo
            echo "── згенерований sql.cf ──"
            cat "$SQL_CF"
            echo
            echo "── spamassassin --lint ──"
            if spamassassin --lint 2>&1; then
                echo "(порожньо вище = помилок немає)"
            else
                echo "(--lint завершився з помилкою, див. рядки вище)"
            fi
        } | mask
        # Код виходу беремо з самого --lint, а не з конвеєра: інакше
        # зламаний конфіг виглядав би успішним, бо sed завжди успішний.
        spamassassin --lint >/dev/null 2>&1
        exit $?
        ;;
    *)       die "невідомий аргумент '$1'; умію лише 'check'" ;;
esac

# ── Чи є взагалі чим запускатись ──────────────────────────────────────
# Перевіряємо ДО старту, щоб повідомлення було про причину, а не про
# наслідок. Уже спіймались: `spamd` у Debian 12+ лежить в ОКРЕМОМУ
# пакеті `spamd`, не в `spamassassin`, і без нього контейнер крутився в
# restart-loop із `command not found`, тоді як конфіг був валідний і
# `spamassassin --lint` проходив чисто.
for bin in spamd spamass-milter; do
    command -v "$bin" >/dev/null 2>&1 || die "у образі немає '$bin'.
Демон spamd і мілтер — ОКРЕМІ пакети Debian (spamd, spamass-milter), а
пакет spamassassin містить лише Perl-модулі, правила й sa-learn.
Перевір _images/spamassassin/Dockerfile і перезбери: ./mailctl build"
done

syslog_to_stderr

# ── spamd ─────────────────────────────────────────────────────────────
# --listen на loopback: мілтер у ЦЬОМУ Ж контейнері, тобто один
# мережевий стек — той самий погоджений виняток, що для пари
# postfix+dovecot (рішення №11). Решті мережі групи сканер не видно.
#
# --sql-config і --nouser-config: prefs беруться з SQL, а не з
# ~/.spamassassin кожного користувача, якого тут усе одно немає.
# ┌───────────────────────────────────────────────────────────────────┐
# │ ЧОМУ spamd ТЕПЕР СЛУХАЄ НЕ ЛИШЕ LOOPBACK (рішення №34).           │
# │                                                                   │
# │ Донавчання приходить від Dovecot, а він живе в netns ПОСТФІКСА —  │
# │ тобто в іншому мережевому стеку, і 127.0.0.1 для нього це не ми.  │
# │ Мілтер при цьому поруч, у цьому ж контейнері, тож йому loopback   │
# │ лишається (рішення №11 — та сама логіка).                         │
# │                                                                   │
# │ --allow-tell вмикає команду TELL, тобто навчання. І ось ціна,     │
# │ словами man spamd: «spamd always trusts the username passed in    │
# │ (unless --auth-ident is used), so clients could maliciously learn │
# │ messages for other users». Отже досяжність порту = можливість     │
# │ зіпсувати bayes будь-кому, і ще й розучити (TELL умієть forget).  │
# │                                                                   │
# │ Тому контроль доступу — ACL САМОГО spamd, а не надія на те, що    │
# │ мережа внутрішня: --allowed-ips пускає рівно loopback і адресу    │
# │ постфікса. Roundcube (.50) і гість-проксі виключені.              │
# │                                                                   │
# │ Чому --listen=0.0.0.0, а не ${INTERNAL_PREFIX}.33: власна адреса  │
# │ цього контейнера задана в шаблоні compose, і друга її копія тут   │
# │ розійшлася б із першою мовчки. Фактичний доступ однаково ріже     │
# │ ACL, а назовні 783 не публікується ніде.                          │
# └───────────────────────────────────────────────────────────────────┘
say "запускаю spamd (TELL увімкнений, доступ лише з 127.0.0.1 і $INTERNAL_PREFIX.10)"
spamd \
    --syslog=stderr \
    --username=debian-spamd \
    --listen=0.0.0.0:783 \
    --allowed-ips="127.0.0.1,$INTERNAL_PREFIX.10" \
    --allow-tell \
    --sql-config \
    --nouser-config \
    --max-children=5 \
    --helper-home-dir=/var/lib/spamassassin &
SPAMD_PID=$!

# Дати spamd піднятись: мілтер без нього одразу почне сипати помилками.
#
# Але чекати ПОРТ, не перевіряючи сам процес, — погана діагностика: якщо
# spamd упав при старті, у логах буде хвилина тишi, а потім загадкове
# «мілтер не слухає». Тому на кожній ітерації питаємо й процес.
#
# Побічний ефект проби, який треба знати: вона відкриває з'єднання і
# одразу закриває, а spamd це логує як
#   warn: spamd: bad protocol: header error: (closed before headers)
# Цей рядок у логах — НАШ, і він не ознака збою. Шукати йому причину в
# Postfix чи в мілтері не треба.
i=0
while ! (exec 3<>/dev/tcp/127.0.0.1/783) 2>/dev/null; do
    if ! kill -0 "$SPAMD_PID" 2>/dev/null; then
        # `wait` на вже завершеному дочірньому дає його код виходу.
        wait "$SPAMD_PID" 2>/dev/null || code=$?
        die "spamd ПОМЕР при старті (код ${code:-?}) — причина у рядках
вище цього повідомлення. Найчастіше це конфіг: перевір
./mailctl config <група> spamassassin"
    fi
    i=$((i + 1))
    [ "$i" -lt 60 ] || break
    sleep 1
done
# ┌───────────────────────────────────────────────────────────────────┐
# │ ТУТ СТОЯВ `exec 3<&- 2>/dev/null || true`, І ВІН З'ЇДАВ ЛОГИ.     │
# │                                                                   │
# │ `exec` БЕЗ КОМАНДИ застосовує перенаправлення до самого шелла —   │
# │ назавжди. Тобто `2>/dev/null` робив stderr контейнера /dev/null,  │
# │ і всі наступні `say`, включно з повідомленнями наглядача про      │
# │ смерть процесу, зникали. У логах лишалось «запускаю spamd» і      │
# │ тиша, хоч контейнер падав із кодом 1.                             │
# │                                                                   │
# │ Закривати було й нічого: перевірка порту вище робиться в        │
# │ ПІДШЕЛЛІ `( )`, тож fd 3 у цьому шеллі ніколи не відкривався.     │
# └───────────────────────────────────────────────────────────────────┘
[ "$i" -lt 60 ] || say "УВАГА — spamd живий, але за 60 с не почав слухати 783"

# ── spamass-milter ────────────────────────────────────────────────────
# Домен для -e беремо з POSTMASTER_ADDRESS: він гарантовано поштовий
# домен групи (MAIL_HOSTNAME ним НЕ є — на цьому вже спіймались із
# postmaster_address у Dovecot).
SA_DOMAIN=${POSTMASTER_ADDRESS#*@}

# ┌───────────────────────────────────────────────────────────────────┐
# │ -i та -I — не оптимізація, а умова правильності (рішення №31).   │
# │                                                                   │
# │ spamass-milter НЕ відрізняє вхідну пошту від вихідної. На порту   │
# │ 25 ми приймаємо і те, й те (абоненти шлють без авторизації —     │
# │ рішення №20, №30), тож без цих прапорців сканувалась би й         │
# │ вихідна пошта, а per-user prefs шукались би за адресою           │
# │ ЗОВНІШНЬОГО отримувача — тобто не знаходились би ніколи.         │
# │                                                                   │
# │   -I              пропустити автентикованих через SMTP AUTH;      │
# │   -i <мережа>     пропустити пошту з довірених мереж.             │
# │                                                                   │
# │ 127.0.0.0/8 у -i стоїть ЗАВЖДИ, окремо від MYNETWORKS, і це      │
# │ виправлення справжнього дефекту (знайдено на small 2026-11-17).   │
# │                                                                   │
# │ Postfix довіряє loopback завжди: його entrypoint задає            │
# │ `mynetworks = 127.0.0.0/8 $MYNETWORKS`, бо звідти ходить сам      │
# │ Dovecot — пересилання через носія (рішення №37) переінжектується  │
# │ як `submission_host = 127.0.0.1:25`. А -i будувався з ГОЛОГО      │
# │ MYNETWORKS, тобто для постфікса цей лист внутрішній, а для        │
# │ мілтера ні. Наслідок видно в базі: ключами per-user bayes стали   │
# │ ЗОВНІШНІ адреси отримувачів переслання, і bayes_auto_learn писав  │
# │ у ті кошики. Гірше за засмічення те, що другий скан іде з         │
# │ порожніми prefs чужої адреси (поріг 5.0 замість налаштованого     │
# │ носієм), тож лист, який перший скан пропустив, може вийти         │
# │ назовні з X-Spam-Flag: YES — тобто рівно проти того, заради чого  │
# │ існує рішення №37.                                                │
# │                                                                   │
# │ УВАГА: з InternalHosts в OpenDKIM цей список НЕ узгоджений, і це  │
# │ свідомо. Там loopback потрібен (Roundcube і носії), тут — ні:     │
# │ підписати пересланий лист і просканувати його — різні питання.    │
# └───────────────────────────────────────────────────────────────────┘
# ┌───────────────────────────────────────────────────────────────────┐
# │ `-f` ТУТ БУТИ НЕ МОЖЕ, і це перевірено наживо (2026-11-06).       │
# │                                                                   │
# │ У spamass-milter `-f` означає «відгалузитись у фон», а не         │
# │ «лишитись на передньому плані», як я спершу припустив. Батьківський│
# │ процес виходив із кодом 0, наглядач `wait -n` одразу його          │
# │ отримував і клав контейнер — при тому, що мілтер справді слухав    │
# │ 8894. Тобто збій виглядав як «мілтер не стартував», хоч стартував. │
# │                                                                   │
# │ Перевірка нижче лишена саме як сторож проти повернення цього       │
# │ прапорця (чи іншого з тим самим змістом).                         │
# └───────────────────────────────────────────────────────────────────┘
set -- -p "inet:8894" -u nobody -e "$SA_DOMAIN" -I -i 127.0.0.0/8

for net in $MYNETWORKS; do
    case "$net" in
        # IPv6 spamass-milter не розбирає; поки стек по IPv6 не ходить,
        # це не втрата, але мовчки відкидати не можна.
        \[*|*:*) say "УВАГА — пропускаю IPv6-мережу '$net' у -i: spamass-milter її не розбирає" ;;
        *)       set -- "$@" -i "$net" ;;
    esac
done

if [ -n "$MYNETWORKS" ]; then
    say "запускаю spamass-milter (-i: 127.0.0.0/8 + MYNETWORKS, -I для"
    say "автентикованих)"
else
    say "запускаю spamass-milter (-i: лише 127.0.0.0/8 — група не довіряє"
    say "жодній мережі, рішення №30; -I для автентикованих)"
fi
spamass-milter "$@" -- -d 127.0.0.1 -p 783 &
MILTER_PID=$!

# ── Чи мілтер справді слухає ──────────────────────────────────────────
# Це не параноя, а наслідок `milter_default_action = accept` у Postfix:
# мілтер, який не слухає, пропускає пошту без перевірки МОВЧКИ. Отже
# «не слухає» мусить бути гучним тут, а не виявлятись через тиждень.
#
# Порядок перевірок навмисний — порт СПЕРШУ, процес ПОТІМ, бо саме це
# розрізняє три різні збої:
#
#   порт відкритий, батько живий  -> усе гаразд;
#   порт відкритий, батько ПОМЕР  -> мілтер ДЕМОНІЗУВАВСЯ (відгалузився
#                                    і вийшов). Тоді наглядач `wait -n`
#                                    одразу отримає його код і покладе
#                                    контейнер, хоч мілтер працює;
#   порт закритий,  батько помер  -> не стартував; причина вище в логах.
i=0
while ! (exec 3<>/dev/tcp/127.0.0.1/8894) 2>/dev/null; do
    if ! kill -0 "$MILTER_PID" 2>/dev/null; then
        wait "$MILTER_PID" 2>/dev/null || mcode=$?
        die "spamass-milter завершився (код ${mcode:-0}), і 8894 НЕ слухає.
Аргументи були: $*
Перевір їх проти 'spamass-milter -h' у цьому ж образі:
  docker run --rm --entrypoint spamass-milter <образ> -h"
    fi
    i=$((i + 1))
    [ "$i" -lt 30 ] || break
    sleep 1
done

if ! kill -0 "$MILTER_PID" 2>/dev/null; then
    die "spamass-milter ВІДГАЛУЗИВСЯ: 8894 слухає, але процес, який ми
запустили, уже вийшов. Тобто один із переданих прапорців означає
'демонізуватись', і найімовірніший кандидат — '-f'. Контейнер із таким
мілтером однаково непридатний: наглядач не бачить справжнього процесу,
а Docker вважає, що померло щось головне.
Прибрати відповідний прапорець у _images/spamassassin/entrypoint.sh."
fi

[ "$i" -lt 30 ] || say "УВАГА — spamass-milter живий, але за 30 с не почав слухати 8894"

# ── Нагляд ────────────────────────────────────────────────────────────
# Помер будь-який із двох — виходимо з ненульовим кодом, і
# `restart: unless-stopped` підіймає контейнер. Альтернатива (жити
# далі з одним процесом) означала б «контейнер здоровий, пошта не
# сканується» — найгірший можливий стан, бо його не видно.
trap 'kill "$SPAMD_PID" "$MILTER_PID" 2>/dev/null || true' TERM INT

wait -n
code=$?
say "один із процесів завершився (код $code) — зупиняю контейнер"
kill "$SPAMD_PID" "$MILTER_PID" 2>/dev/null || true
exit 1
