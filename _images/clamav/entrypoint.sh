#!/bin/bash
# ─────────────────────────────────────────────────────────────────────
#  Entrypoint образу clamav.
#
#  Три процеси: `clamd` (сканер), `freshclam` (оновлення бази) і
#  `clamav-milter` (адаптер до Postfix). В одному контейнері свідомо —
#  рознести їх не вийде без гіршого: freshclam мусить ПИСАТИ в той
#  самий том, який clamd читає, а мілтер без clamd безсилий.
#
#  Послідовність важлива: без бази clamd не стартує взагалі
#  («no supported database files found»), тому спершу одноразове
#  завантаження, і лише потім демони.
#
#  bash через `wait -n` у наглядачі, як і в spamassassin.
# ─────────────────────────────────────────────────────────────────────
set -eu

SHARED=/etc/clamav/shared
CUSTOM=/etc/clamav/config
DB=/var/lib/clamav
RUN=/run/clamav

die() { echo "clamav-entrypoint: $*" >&2; exit 1; }
say() { echo "clamav-entrypoint: $*" >&2; }

# ── Конфіги: груповий перекриває спільний ─────────────────────────────
# Три файли, і кожен перекривається незалежно: групі може знадобитись
# свій clamav-milter.conf (наприклад інший OnInfected), але той самий
# clamd.conf.
for f in clamd.conf freshclam.conf clamav-milter.conf; do
    if [ -f "$CUSTOM/$f" ]; then
        say "конфіг ГРУПИ $CUSTOM/$f (перекриває спільний)"
        cp "$CUSTOM/$f" "/etc/clamav/$f"
    elif [ -f "$SHARED/$f" ]; then
        cp "$SHARED/$f" "/etc/clamav/$f"
    else
        die "немає ні $CUSTOM/$f, ні $SHARED/$f — перевір GROUP_CONFIG_DIR
у group.env і те, що _configs/ на місці"
    fi
done

install -d -o clamav -g clamav -m 0755 "$RUN" "$DB"

# ── Режим перевірки ───────────────────────────────────────────────────
# Тут він дешевий і корисний: `clamconf` друкує ефективні значення всіх
# трьох конфігів, тобто показує, що саме ClamAV з них прочитав. Базу
# для цього завантажувати не треба.
case "${1:-}" in
    '')      ;;
    check)
        say "режим check: ефективні значення конфігів"
        exec clamconf
        ;;
    *)       die "невідомий аргумент '$1'; умію лише 'check'" ;;
esac

# ── База вірусів ──────────────────────────────────────────────────────
# ┌───────────────────────────────────────────────────────────────────┐
# │ ПЕРШИЙ СТАРТ ГРУПИ ДОВГИЙ, і це не збій.                         │
# │                                                                   │
# │ База важить близько гігабайта й у образ не кладеться (вона        │
# │ оновлюється щодня — образ був би застарілим з дня збірки). Отже   │
# │ при першому старті freshclam тягне її з інтернету, і до кінця     │
# │ завантаження мілтера немає, тобто Postfix отримує tempfail на     │
# │ перевірку (OnFail Defer) і відкладає пошту. Відправники           │
# │ повторять — нічого не губиться.                                   │
# │                                                                   │
# │ Якщо завантаження не йде ВЗАГАЛІ, дивитись треба не сюди, а на    │
# │ вихід у мережу: freshclam — єдиний у стеку, хто ініціює HTTPS     │
# │ назовні не для пошти, і він піде з адреси PRIMARY_NET групи.      │
# └───────────────────────────────────────────────────────────────────┘
if ! ls "$DB"/*.c[vl]d >/dev/null 2>&1; then
    say "бази вірусів немає — завантажую (це довго, близько гігабайта;"
    say "до кінця завантаження пошта відкладається, а не губиться)"
    # Одноразово, не демоном: --no-warnings прибирає шум про те, що
    # clamd ще не запущений і йому нема кого повідомляти.
    freshclam --stdout --no-warnings \
        || die "не вдалось завантажити базу вірусів. Перевір вихід у мережу
з цієї групи: freshclam ходить HTTPS на database.clamav.net з адреси
PRIMARY_NET, і якщо на хості є nft-правила на вихідний трафік групи,
цей напрямок мусить бути дозволений"
fi

# ── Демони ────────────────────────────────────────────────────────────
say "запускаю clamd"
clamd --config-file=/etc/clamav/clamd.conf &
CLAMD_PID=$!

# clamd читає базу в пам'ять, і це хвилини при холодному старті. Мілтер
# без нього відповідав би tempfail на все.
#
# Чекаємо не лише порт, а й сам процес: якщо clamd упав, у логах інакше
# буде п'ять хвилин тишi замість причини.
i=0
while ! (exec 3<>/dev/tcp/127.0.0.1/3310) 2>/dev/null; do
    if ! kill -0 "$CLAMD_PID" 2>/dev/null; then
        wait "$CLAMD_PID" 2>/dev/null || code=$?
        die "clamd ПОМЕР при старті (код ${code:-?}) — причина в рядках вище"
    fi
    i=$((i + 1))
    [ "$i" -lt 300 ] || break
    sleep 1
done
# ┌───────────────────────────────────────────────────────────────────┐
# │ ТУТ СТОЯВ `exec 3<&- 2>/dev/null || true` — і він З'ЇДАВ ЛОГИ.    │
# │                                                                   │
# │ `exec` без команди застосовує перенаправлення до САМОГО ШЕЛЛА, і  │
# │ назавжди: `2>/dev/null` робив stderr контейнера /dev/null. Через  │
# │ це всі наступні `say` (включно з «запускаю freshclam» і з         │
# │ повідомленням наглядача про смерть процесу) зникали. Демони при   │
# │ цьому писали свої логи самі, тож збій виглядав «нормальним».      │
# │                                                                   │
# │ Закривати було й нічого: перевірка порту робиться в ПІДШЕЛЛІ,     │
# │ тож fd 3 у цьому шеллі не відкривався.                            │
# └───────────────────────────────────────────────────────────────────┘
[ "$i" -lt 300 ] || say "УВАГА — clamd живий, але за 300 с не почав слухати 3310"

say "запускаю freshclam (демон)"
freshclam --daemon --stdout --no-warnings &
FRESH_PID=$!

say "запускаю clamav-milter"
clamav-milter --config-file=/etc/clamav/clamav-milter.conf &
MILTER_PID=$!

# ── Нагляд ────────────────────────────────────────────────────────────
# Помер будь-який — виходимо, і `restart: unless-stopped` підіймає
# контейнер. Жити далі з двома з трьох означало б «контейнер здоровий,
# вірусів не ловимо» — стан, який не видно, а тому найгірший.
#
# Увага на freshclam: якщо помре саме він, пошта далі перевіряється, але
# базою, яка щодня старіє. Саме тому він теж під наглядом, а не
# «необов'язковий».
trap 'kill "$CLAMD_PID" "$FRESH_PID" "$MILTER_PID" 2>/dev/null || true' TERM INT

wait -n
code=$?
say "один із процесів завершився (код $code) — зупиняю контейнер"
kill "$CLAMD_PID" "$FRESH_PID" "$MILTER_PID" 2>/dev/null || true
exit 1
