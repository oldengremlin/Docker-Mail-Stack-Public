не працюватиме, а Dovecot скаже лише «program not found»"
install -m 0755 "$src" "$PIPE_DIR/spamc-learn"

# `spamc` мусить бути в образі — інакше програма впаде вже після того,
# як користувач переклав лист, тобто мовчки для нього. Перевіряємо тут,
# разом з усім іншим, що потрібне для донавчання.
command -v spamc >/dev/null 2>&1 \
