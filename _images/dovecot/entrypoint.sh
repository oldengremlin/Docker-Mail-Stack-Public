#!/bin/sh
# ─────────────────────────────────────────────────────────────────────
#  Entrypoint образу dovecot.
#
#  Пише /etc/dovecot/generated.conf — ту частину конфігу, якої в
#  репозиторії бути не може (пароль до БД) або яка є параметром групи
#  (uid/gid власника скриньок, адреси для listen, FQDN). Статична
#  частина приходить змонтованою в /etc/dovecot/custom/dovecot.conf і
#  підключає цей файл через !include.
#
#  Чому генерація, а не готовий файл: у 2.4 окремого
#  dovecot-sql.conf.ext більше немає — блок підключення до БД живе
#  всередині конфігу, разом із паролем.
# ─────────────────────────────────────────────────────────────────────
set -eu

# Спільна база плюс перекриття групи. Беремо груповий файл, якщо він
# є, інакше спільний — і КАЖЕМО В ЛОГ, який саме взяли. Мовчазне
# перекриття було б тією самою пасткою, через яку все це й з'явилось:
# правка в _configs/ не діє, бо в групі лежить стара копія.
SHARED_CONF=/etc/dovecot/shared/dovecot.conf
OWN_CONF=/etc/dovecot/custom/dovecot.conf
# Копіюємо на КАНОНІЧНЕ місце, а не запускаємось із -c.
#
# Причина не в естетиці: `doveadm` і `doveconf` без -c читають саме
# /etc/dovecot/dovecot.conf. Якби наш конфіг лишався лише в
# /etc/dovecot/custom/, то кожна діагностична команда
# (`doveadm user`, `doveadm auth test`, `doveadm search`) без -c
# працювала б з ПАКЕТНИМ конфігом — тобто з іншою БД, іншим namespace і
# іншим mail_path, і відповідала б упевнено й неправильно.
# Пакетний файл включає conf.d/*, наш — ні, тож рішення №26 від
# перезапису не страдає.
CONF=/etc/dovecot/dovecot.conf
GEN=/etc/dovecot/generated.conf
# Куда кладуться адміністраторські .sieve. Одна константа на два
# вжитки (шлях у generated.conf і шлях установки нижче): дві копії
# розійшлися б мовчки, а симптом був би «before-скрипт не діє».
SIEVE_DIR_FOR_CONF=/etc/dovecot/sieve
TLS_DIR=/etc/dovecot/tls

die() { echo "dovecot-entrypoint: $*" >&2; exit 1; }

if [ -f "$OWN_CONF" ]; then
    CONF_SRC=$OWN_CONF
    echo "dovecot-entrypoint: конфіг ГРУПИ $OWN_CONF (перекриває спільний)" >&2
elif [ -f "$SHARED_CONF" ]; then
    CONF_SRC=$SHARED_CONF
else
    die "немає ні $OWN_CONF, ні $SHARED_CONF — перевір GROUP_CONFIG_DIR у
group.env і те, що _configs/ на місці"
fi
cp "$CONF_SRC" "$CONF"

# ── Обов'язкові змінні ────────────────────────────────────────────────
# Перевіряємо всі разом і падаємо з повним списком: інакше запуск
# перетворюється на «виправив одну, дізнався про наступну».
missing=
for v in MYSQL_HOST MYSQL_DB MYSQL_USER MYSQL_PASSWORD \
         LISTEN_ADDRESSES VMAIL_UID VMAIL_GID MAIL_HOSTNAME \
         INTERNAL_PREFIX \
         POSTMASTER_ADDRESS SIEVE_MAX_REDIRECTS \
         AUTH_ALLOW_WEAK_SCHEMES; do
    eval "val=\${$v:-}"
    [ -n "$val" ] || missing="$missing $v"
done
[ -z "$missing" ] || die "не задані змінні:$missing"

case "$VMAIL_UID" in *[!0-9]*) die "VMAIL_UID='$VMAIL_UID' мусить бути числом";; esac
case "$VMAIL_GID" in *[!0-9]*) die "VMAIL_GID='$VMAIL_GID' мусить бути числом";; esac

# Не число або нуль — Dovecot або не стартує, або тихо забороняє
# будь-який redirect, і пересилання зникає без жодного повідомлення.
case "$SIEVE_MAX_REDIRECTS" in
    *[!0-9]*|0|'') die "SIEVE_MAX_REDIRECTS='$SIEVE_MAX_REDIRECTS' мусить
бути цілим від 1";;
esac

# Dovecot прийме лише yes/no. Опечатка на кшталт `true` дала б не
# помилку конфігу, а відмову старту — тобто вся група лягла б через
# один символ.
case "$AUTH_ALLOW_WEAK_SCHEMES" in
    yes|no) ;;
    *) die "AUTH_ALLOW_WEAK_SCHEMES='$AUTH_ALLOW_WEAK_SCHEMES' — умію yes і no";;
esac
[ "$AUTH_ALLOW_WEAK_SCHEMES" = no ] || echo "dovecot-entrypoint: СЛАБКІ схеми" \
    "паролів ДОЗВОЛЕНІ (MD5-CRYPT, DES-CRYPT) — потрібно для перенесених" \
    "історичних хешів, рішення №25" >&2

# Пароль іде в конфіг як значення параметра. '#' у Dovecot починає
# коментар і в середині рядка, а перенос рядка розірве блок — у обох
# випадках помилка була б не «невірний пароль», а зламаний конфіг.
# Краще відмовитись одразу й зрозуміло.
case "$MYSQL_PASSWORD" in
    *'#'*)  die "MYSQL_PASSWORD містить '#' — у конфізі Dovecot це початок
коментаря. Змінити пароль у group.env";;
    *'
'*)        die "MYSQL_PASSWORD містить перенос рядка";;
esac

# ── listen ────────────────────────────────────────────────────────────
# LISTEN_ADDRESSES приходить через ПРОБІЛ (генерує mailctl), Dovecot
# хоче через кому. 127.0.0.1 додаємо завжди: на ньому живуть LMTP і
# SASL-auth для постфікса (рішення №11).
#
# Явний перелік, а не '*': у netns групи адрес більше, ніж поштових.
#
# ┌───────────────────────────────────────────────────────────────────┐
# │ INTERNAL_PREFIX.10 у списку — СВІДОМА зміна раніше прийнятого,    │
# │ а не недогляд. Тут раніше стояв лише публічний набір плюс         │
# │ loopback, із обґрунтуванням «щоб компрометація проксі не дала     │
# │ доступу до IMAP кожної групи».                                    │
# │                                                                   │
# │ Чому змінено: Roundcube за рішенням №5 винесений з netns          │
# │ постфікса й живе звичайним контейнером на internal. Достукатись   │
# │ до Dovecot він може ЛИШЕ по internal-адресі:                      │
# │   - на 127.0.0.1 — ні, це інший network namespace;                │
# │   - на публічну адресу групи — ні, пакет пішов би через шлюз      │
# │     bridge на хост, а хост власних ipvlan-слейвів не бачить       │
# │     (записана пастка проєкту);                                    │
# │   - у netns постфікса його не повернути — це прямо заборонено     │
# │     рішенням №5, бо там він слухав би :80 і на білій адресі.      │
# │ Отже без цього рядка вебмейл неможливий КОНСТРУКТИВНО, і жодна    │
# │ правка його конфігу цього не змінює.                              │
# │                                                                   │
# │ Що саме стало видно решті internal (разом із гостем-проксі):      │
# │ 110/143/993/995 і 4190. Що НЕ стало: LMTP (24) і SASL-auth        │
# │ (12345) — вони лишаються на 127.0.0.1 за рішенням №11, тобто      │
# │ найчутливіше не розширилось. Для IMAP потрібен пароль, для        │
# │ SASL-auth постфікса — ні.                                         │
# │                                                                   │
# │ Звузити до «лише 143 і 4190» можна було б per-listener, але це    │
# │ означало б тримати повний список адрес у трьох місцях конфігу —   │
# │ саме той клас розсинхрону, якого проєкт уникає всюди інде.        │
# └───────────────────────────────────────────────────────────────────┘
listen=$(echo "$LISTEN_ADDRESSES" | tr -s ' ' ',' | sed 's/^,//; s/,$//')
listen="${listen},127.0.0.1,${INTERNAL_PREFIX}.10"

# ── Автентифікація у ВІДКРИТОМУ вигляді, точково ──────────────────────
# Рішення №14 вимагає TLS, і це лишається дефолтом. Але уточнення
# власника (2026-11-13) зробило виняток ПАРАМЕТРОМ ГРУПИ: на office
# більшість офісу ходить голим POP3, на isp — 312 абонентів
# провайдера, яким «перенастройте клієнт» сказати нікому.
#
# Блок `remote <мережа>` звіряється з адресою КЛІЄНТА, тож дозвіл не
# поширюється на решту світу. Синтаксис звірено на образі, і звірка
# мала власний контроль: вигаданий блок дає `Unknown section name`, а
# вигаданий параметр усередині — `Unknown setting`. Тобто тут doveconf
# валідує і секції, і параметри, на відміну від `cause` в imapsieve.
#
# Порожній CLEARTEXT_NETWORKS (дефолт, і так на small) не породжує
# жодного блоку — поведінка не змінюється ні на біт.
# ОКРЕМЕ СЛОВО `any` — глобальний дозвіл, без жодного remote-блоку.
# Воно існує не для зручності: на isp точковий список НЕМОЖЛИВИЙ.
# Із десяти активних абонентів один заходить приблизно зі 130 адрес за
# місяць (Київстар, Укртелеком, мобільні — динаміка по всій країні),
# троє — це Gmail, що забирає пошту по POP3, ще один — Cloudflare.
# Перелічити це мережами не вийде, а жорстке `no` означало б, що в
# день міграції пошта зникає в усіх десяти.
#
# `0.0.0.0/0` для цього НЕ годиться, і заборона на нього в
# check_net_list() лишається: для MYNETWORKS вона несуча (це був би
# відкритий релей), а два списки з однаковим форматом і протилежним
# змістом мусять мати різні способи сказати «усі». Слово читається
# однозначно й шукається grep-ом.
: "${CLEARTEXT_NETWORKS:=}"
cleartext_blocks=''
cleartext_global='no'
case "$CLEARTEXT_NETWORKS" in
    any|ANY|Any)
        cleartext_global='yes'
        echo "dovecot-entrypoint: автентифікація БЕЗ TLS дозволена" \
             "ГЛОБАЛЬНО (CLEARTEXT_NETWORKS=any) — паролі йдуть" \
             "ВІДКРИТИМ ТЕКСТОМ з будь-якої адреси. Рішення №14," \
             "уточнення 2026-11-13; ціна названа й прийнята власником" >&2
        ;;
    '')
        ;;
    *)
        for net in $CLEARTEXT_NETWORKS; do
            cleartext_blocks="${cleartext_blocks}
remote ${net} {
  auth_allow_cleartext = yes
}"
        done
        echo "dovecot-entrypoint: автентифікація БЕЗ TLS дозволена для:" \
             "${CLEARTEXT_NETWORKS} — паролі звідти йдуть ВІДКРИТИМ ТЕКСТОМ" \
             "(рішення №14, уточнення 2026-11-13)" >&2
        ;;
esac

# ── ssl ───────────────────────────────────────────────────────────────
# ssl МУСИТЬ походити з того самого джерела, що auth_allow_cleartext, і
# це не гігієна. Dovecot 2.4 перевіряє пару на суперечність і падає
# FATAL-ом:
#
#   Error: auth_allow_cleartext=yes has no effect with ssl=required
#   Fatal: Error in configuration file /etc/dovecot/dovecot.conf
#
# Тобто група з CLEARTEXT_NETWORKS=any просто НЕ СТАРТУЄ, поки ssl
# лишається required. Спіймалось на першому ж запуску isp — на small
# видно не було, бо там дозвіл порожній і пара узгоджена сама собою.
#
# ssl ПРИБРАНИЙ зі статичного dovecot.conf із тієї ж причини, що й
# auth_allow_cleartext: !include generated.conf стоїть на ПОЧАТКУ
# статичного файла, а Dovecot для скалярів бере ПОСЛІДНЄ значення —
# отже літерал унизу затирав би те, що прийшло з env.
#
# ЦІНА ДЛЯ ТОЧКОВИХ СПИСКІВ НАЗВАНА: ssl глобальний, тож при
# CLEARTEXT_NETWORKS=<мережі> TLS перестає бути обов'язковим і для
# тих, кого в списку немає. Чи приймає Dovecot 2.4 ssl усередині
# remote { } — НЕ перевірено; до перевірки точковий список поводиться
# як any у частині ssl. Для isp це не важить (там any), для office
# треба звірити на образі.
if [ "$cleartext_global" = yes ] || [ -n "$cleartext_blocks" ]; then
    ssl_mode='yes'
else
    ssl_mode='required'
fi

# ── Глобальне розкладання спаму (SPAM_TO_JUNK) ───────────────────────
# Параметр ГРУПИ, дефолт «no», тобто без нього нічого не змінюється.
#
# Чому не завжди: на isp-подібній групі всі активні клієнти POP3, а
# POP3 бачить лише INBOX — хибне спрацювання поїхало б у теку, якої
# абонент не побачить ніколи (рішення №21). На office же глобальний
# скрипт діє на всіх 235, тож НЕ відтворити його означало б, що спам
# раптом посипався всім в INBOX.
#
# Скрипт кладеться в образ завжди (і компілюється завжди — помилка в
# ньому мусить валити старт, а не чекати першого спам-листа), а оце
# лише ПІДКЛЮЧАЄ його як before-скрипт.
: "${SPAM_TO_JUNK:=no}"
global_spam_block=
case "$SPAM_TO_JUNK" in
    no)  echo "dovecot-entrypoint: SPAM_TO_JUNK=no — глобального" \
             "розкладання спаму НЕМА; спам лягає в Junk лише тим, у кого" \
             "є власне правило" >&2
         ;;
    yes) global_spam_block="
# Глобальний before-скрипт: спам у Junk ДО користувацьких правил.
# Синтаксис блоку — з пакетного conf.d/90-sieve.conf, не з пам'яті.
sieve_script global-spam {
  type   = before
  driver = file
  path   = ${SIEVE_DIR_FOR_CONF}/global-spam.sieve
}"
         echo "dovecot-entrypoint: SPAM_TO_JUNK=yes — спам у Junk" \
             "глобально, ДО користувацьких правил (before-скрипт)" >&2
         ;;
    *)   die "SPAM_TO_JUNK='$SPAM_TO_JUNK' — умію yes і no";;
esac


# sieve_global_extensions ЗАВЖДИ звідси, а не зі статики — той самий
# урок, що з `ssl` і `auth_allow_cleartext` 18.11: два джерела одного
# блоку розійшлись б МОВЧКИ, а тут ціна розходу — або звіт не
# пішов, або розширення доступне всім користувачам.
sieve_ext_block="sieve_global_extensions {
  vnd.dovecot.pipe = yes"
sieve_ext_block="$sieve_ext_block
}"

umask 077
cat > "$GEN" <<CONF
# ЗГЕНЕРОВАНО entrypoint-ом із env. Не редагувати: перезаписується на
# кожному старті контейнера. Статична частина — у
# /etc/dovecot/custom/dovecot.conf.

hostname = ${MAIL_HOSTNAME}

# Адреса для конвертів відмов, які складає сам Dovecot (LMTP, vacation).
# Беремо з env, а НЕ складаємо з MAIL_HOSTNAME: postmaster@mail.small.example.org
# нікуди не доставляється, бо mail.small.example.org не поштовий домен групи.
postmaster_address = ${POSTMASTER_ADDRESS}

listen = ${listen}

# Власник файлів у /var/mail. РІЗНИЙ між групами, і відрізняється не
# лише число, а й ім'я користувача (small: mail/8, office: virtual/5000)
# — тому числами (рішення №8).
mail_uid = ${VMAIL_UID}
mail_gid = ${VMAIL_GID}

# Без цього Dovecot відмовить групі з низьким uid: дефолт
# first_valid_uid = 500, а small тримає скриньки на системному mail (8).
# Симптом був би «userdb returned uid 8 but first_valid_uid is 500», і
# шукати його в конфізі, якого ми не писали, — задоволення нижче
# середнього.
first_valid_uid = ${VMAIL_UID}
first_valid_gid = ${VMAIL_GID}

# Скільки redirect дозволено ОДНОМУ скрипту. Параметр ГРУПИ, бо носії
# пересилання (db-convert.pl --forward=sieve) впираються в нього тим
# швидше, чим довший був список аліаса: на small info@charity.example.org має
# рівно чотири, тобто дефолт Pigeonhole вичерпано.
#
# Перевищення не обрізає список, а ВАЛИТЬ виконання скрипта цілком —
# лист не піде НІКОМУ. Тому ліміт і піднімають заздалегідь, а не після
# першої скарги; «mailctl health» показує запас по кожному скрипту.
#
# Ліміт ГЛОБАЛЬНИЙ: діє і на користувацькі фільтри з ManageSieve, не
# лише на наші носії. Звідси ж причина не опускати його автоматично —
# зламався б чужий фільтр, і мовчки.
sieve_max_redirects = ${SIEVE_MAX_REDIRECTS}

# Слабкі схеми зберігання паролів. У 2.4 з'явився цей прапорець із
# дефолтом «no», і під забороною саме MD5-CRYPT та DES-CRYPT (PLAIN і
# CRAM-MD5 не зачеплені). Для small це байдуже, а на isp під
# забороною опиняються 262 записи з 312 — тобто при «no» більшість
# абонентів просто не заходить, і симптом буде «пароль не підходить»,
# а не «схема заборонена».
#
# Прапорець ГЛОБАЛЬНИЙ: він не вмикає слабкі схеми вибірково, а знімає
# заборону на всі. Тому він же — аргумент перехешувати те, що лежить
# відкритим текстом (рішення №25).
auth_allow_weak_schemes = ${AUTH_ALLOW_WEAK_SCHEMES}

# Ціна рішення №14: на 110/143 обов'язковий STARTTLS.
#
# ЧОМУ ЦЕЙ РЯДОК ТУТ, А НЕ В СТАТИЧНОМУ dovecot.conf, де він і стояв.
# «!include generated.conf» робиться на початку статичного файла, а
# Dovecot для скалярів бере ПОСЛІДНЄ значення — тобто літерал
# «auth_allow_cleartext = no» нижче затирав би все, що прийшло з env.
# Для remote-блоків це не було видно (умовна секція перебиває глобальне
# значення незалежно від порядку файлів), і саме тому пастка дочекалась
# «any»: симптом був би «any в group.env стоїть, абоненти не заходять,
# конфіг валідний». Контроль ефективного значення — нижче, перед exec.
auth_allow_cleartext = ${cleartext_global}

# Обов'язковість TLS. Виводиться з CLEARTEXT_NETWORKS тим самим кодом,
# що й рядок вище: Dovecot падає, якщо дозволити відкритий пароль і
# водночас вимагати TLS. Довгий розбір — в entrypoint.
ssl = ${ssl_mode}

# Блок підключення до БД. Ім'я блоку — це ХОСТ (або шлях до сокета), а
