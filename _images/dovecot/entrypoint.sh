в _images/dovecot/Dockerfile і перезібрати: ./mailctl build"

# ┌───────────────────────────────────────────────────────────────────┐
# │ Компілюємо скрипти ТУТ, а не лишаємо це Dovecot на рантайм.       │
# │                                                                   │
# │ Інакше помилка в .sieve виявилась би в найгірший момент: лист     │
# │ переклали, подія спрацювала, скрипт не скомпілювався — і          │
# │ навчання тихо не відбулось. Користувач при цьому бачить, що лист  │
# │ лежить у Junk, і вважає, що все гаразд.                           │
# │                                                                   │
# │ `sievec` тут робить дві речі одночасно: кладе .svbin поруч (щоб   │
# │ Dovecot не компілював на кожен лист) і ГУЧНО падає на старті, якщо│
# │ у скрипті помилка.                                                │
# └───────────────────────────────────────────────────────────────────┘
for f in "$SIEVE_DIR"/*.sieve; do
    sievec "$f" || die "не компілюється $f — те, для чого він існує
(донавчання або глобальне розкладання спаму), не працювало б МОВЧКИ,
тому не запускаємось. Текст помилки вище."
done

# ── Режим перевірки ───────────────────────────────────────────────────
# `docker run --rm ... mail/dovecot:trixie check` друкує ЕФЕКТИВНИЙ
# конфіг і виходить, нічого не запускаючи. Потрібен саме тому, що
# звичайний шлях діагностики тут не працює: якщо конфіг зламаний,
# контейнер крутиться в restart-loop, і `docker exec` у нього вже не
# зайти («is restarting, wait until the container is running»).
# Викликається через `mailctl config <group>`.
# Аргументи розбираємо ЯВНО й невідомі відкидаємо. Раніше останнім
# рядком стояв запуск dovecot із "$@" на кінці, і це дало рівно той
# клас помилки, якого ми в цьому проєкті намагаємось позбутись:
# контейнеру передали `check` на НЕперезібраному образі, аргумент
# проїхав наскрізь у dovecot, і повідомлення вийшло про опцію -F —
# тобто про те, до чого проблема не мала жодного стосунку.
case "${1:-}" in
    '')      ;;                     # звичайний старт
    check)
        # Без жодних «конфіг валідний» до самої перевірки: doveconf або
        # надрукує ефективні значення, або скаже, в якому рядку помилка.
        exec doveconf -n
        ;;
    *)  die "невідомий аргумент '$1'. Приймаємо лише 'check' (надрукувати
ефективний конфіг і вийти) або нічого (запустити Dovecot)";;
esac

# ── Перевірка конфігу перед запуском ──────────────────────────────────
# doveconf падає на синтаксичній помилці й пише, у якому рядку. Краще
# отримати це одразу, ніж «контейнер перезапускається» в docker ps.
doveconf -n >/dev/null \
    || die "конфіг не проходить doveconf — дивись повідомлення вище"

# Контроль: чи ефективне значення справді те, що ми хотіли. Проба
# потрібна саме тут, бо помилка цього класу МОВЧАЗНА — конфіг валідний,
# параметр у group.env стоїть, а діє протилежне (див. коментар над
# auth_allow_cleartext у generated.conf).
eff=$(doveconf -h auth_allow_cleartext 2>/dev/null)
if [ "$eff" != "$cleartext_global" ]; then
    die "auth_allow_cleartext ефективно '$eff', а має бути" \
        "'$cleartext_global' — хтось перевизначив його ПІСЛЯ" \
        "!include generated.conf у dovecot.conf"
fi

# ssl — те саме, і перевіряється ОКРЕМО, а не разом із попереднім:
# якщо колись з'явиться ssl усередині remote { }, глобальне значення
# зміниться, і відмова мусить назвати саме його.
eff=$(doveconf -h ssl 2>/dev/null)
if [ "$eff" != "$ssl_mode" ]; then
    die "ssl ефективно '$eff', а має бути '$ssl_mode' — найімовірніше" \
        "літерал 'ssl =' повернувся у статичний dovecot.conf, нижче" \
        "!include generated.conf"
fi

# Кажемо, що саме запускаємо: якщо впаде вже сам dovecot, у лозі буде
# видно рядок запуску, а не лише його невдоволення.
echo "dovecot-entrypoint: exec dovecot -F" >&2
exec dovecot -F
