# ── /var/mail ─────────────────────────────────────────────────────────
# Том монтується в /var/mail (рішення №8). При першому старті Docker
# створює його з правами з образу (root:mail), і Dovecot не зміг би
# створити теку домену.
#
# НЕ рекурсивно й навмисно: на мігрованій групі тут десятки тисяч
# файлів, і chown -R на кожному старті — це хвилини вводу-виводу на
# порожньому місці. Права всередині — відповідальність міграції.
if [ -d /var/mail ]; then
    owner=$(stat -c '%u:%g' /var/mail)
    if [ "$owner" != "${VMAIL_UID}:${VMAIL_GID}" ]; then
        echo "dovecot-entrypoint: /var/mail має власника $owner," \
             "ставлю ${VMAIL_UID}:${VMAIL_GID} (тільки сама тека, не рекурсивно)" >&2
        chown "${VMAIL_UID}:${VMAIL_GID}" /var/mail
    fi
fi

# ── TLS ───────────────────────────────────────────────────────────────
# ЗАГЛУШКА, поки сертифікат не випущений. Без сертифіката Dovecot не стартує взагалі,
# бо auth_allow_cleartext = no: увійти не зміг би ніхто, і діагноз був
# би «сервіс не піднявся».
#
# Том tls-certs СПІЛЬНИЙ із postfix, тож цей блок виконують обидва
# контейнери, і стартують вони майже одночасно. Тому генеруємо в
# тимчасові імена й ставимо на місце через `mv`: він атомарний у межах
# однієї ФС, отже другий контейнер або побачить готову пару файлів, або
# не побачить нічого — але ніколи напівзаписаний ключ. Без цього
# найпоширеніший симптом був би «іноді при старті сертифікат битий».
#
# Справжній сертифікат кладе сюди `mailctl certs` (TODO п.7), ПІД ТИМИ
# Ж іменами — certbot називає свої файли так само. Отже щойно він
# з'явиться, цей блок просто перестане спрацьовувати, а конфіги не
# змінюються взагалі.
if [ ! -s "$TLS_DIR/privkey.pem" ] || [ ! -s "$TLS_DIR/fullchain.pem" ]; then
    mkdir -p "$TLS_DIR"
    echo "dovecot-entrypoint: УВАГА — сертифіката немає, генерую" \
         "САМОПІДПИСАНИЙ для ${MAIL_HOSTNAME}. Клієнти побачать" \
         "попередження; нормально лише до «mailctl certs»." >&2
    tmp=$(mktemp -d "$TLS_DIR/.stub.XXXXXX") \
        || die "не можу створити тимчасову теку в $TLS_DIR"
    if openssl req -new -x509 -days 90 -nodes -newkey rsa:2048 \
        -subj "/CN=${MAIL_HOSTNAME}" \
        -addext "subjectAltName=DNS:${MAIL_HOSTNAME}" \
        -keyout "$tmp/privkey.pem" \
        -out    "$tmp/fullchain.pem" 2>/dev/null
    then
        chmod 600 "$tmp/privkey.pem"
        chmod 644 "$tmp/fullchain.pem"
        mv "$tmp/privkey.pem"   "$TLS_DIR/privkey.pem"
        mv "$tmp/fullchain.pem" "$TLS_DIR/fullchain.pem"
    else
        rm -rf "$tmp"
        die "не вдалось згенерувати самопідписаний сертифікат"
    fi
    rm -rf "$tmp"
fi

# ── Донавчання антиспаму: скрипти й програма (рішення №34) ────────────
# Копіюємо, а НЕ монтуємо, і причин три:
#   1. програмі в sieve_pipe_bin_dir потрібен біт +x. Через `install -m`
#      він наш, а не той, що випадково лежить у git;
#   2. Dovecot компілює адміністраторський скрипт у .svbin ПОРУЧ із
#      ним. Каталог, змонтований read-only з репозиторію, на це дав би
#      попередження при кожному запуску листа;
#   3. груповий файл мусить перекривати спільний — та сама логіка, що
#      для dovecot.conf вище, включно з рядком у лог.
SIEVE_DIR=$SIEVE_DIR_FOR_CONF
PIPE_DIR=/usr/share/dovecot-pigeonhole/sieve   # шлях ПАКЕТНИЙ, див. dovecot.conf
install -d -m 0755 "$SIEVE_DIR" "$PIPE_DIR"

pick() {                 # $1 = відносний шлях; друкує обраний файл
    if [ -f "/etc/dovecot/custom/$1" ]; then
        echo "dovecot-entrypoint: $1 — версія ГРУПИ (перекриває спільну)" >&2
        echo "/etc/dovecot/custom/$1"
    elif [ -f "/etc/dovecot/shared/$1" ]; then
        echo "/etc/dovecot/shared/$1"
    fi
}

for f in report-spam.sieve report-ham.sieve global-spam.sieve; do
    src=$(pick "$f") || true
    [ -n "$src" ] || die "немає $f ні в групі, ні в _configs/dovecot/ —
а на нього посилається dovecot.conf (sieve_script report-*)"
    install -m 0644 "$src" "$SIEVE_DIR/$f"
done


