#!/bin/bash
# ─────────────────────────────────────────────────────────────────────
#  Entrypoint образу postgrey — greylisting як policy-сервіс Postfix.
#
#  Усі неочевидні значення нижче взяті з `postgrey --help` НА ЦЬОМУ
#  образі, не з пам'яті й не з документації в інтернеті.
# ─────────────────────────────────────────────────────────────────────
set -eu

SHARED=/etc/postgrey/shared
CUSTOM=/etc/postgrey/config
DBDIR=/var/lib/postgrey
PORT=10023

die() { echo "postgrey-entrypoint: $*" >&2; exit 1; }
say() { echo "postgrey-entrypoint: $*" >&2; }

command -v postgrey >/dev/null 2>&1 \
    || die "у образі немає postgrey — перевір Dockerfile і ./mailctl build"

# ┌───────────────────────────────────────────────────────────────────┐
# │ ПЕРЕВІРЯЄМО PERL-МОДУЛЬ, А НЕ ПАКЕТ. На цьому вже спіймались.    │
# │                                                                   │
# │ `postgrey --help` у образі друкував попередження                  │
# │   Attempt to call undefined import method ... "IO::Multiplex"     │
# │ і все одно показував довідку — бо вона друкується ДО старту       │
# │ сервера. Сам сервер на цьому ліг би.                              │
# │                                                                   │
# │ Причина — `--no-install-recommends` (рішення №1): IO::Multiplex   │
# │ приходить рекомендацією, а не залежністю. Той самий клас, що      │
# │ `spamd` окремим пакетом у Debian 12+.                             │
# │                                                                   │
# │ Перевіряємо ОБА модулі, хоч бракувало лише одного. Другий         │
# │ (Net::Server::Multiplex) присутній як жорстка залежність          │
# │ postgrey — це видно з того ж повідомлення, яке виникло ВСЕРЕДИНІ  │
# │ його файлу. Але якщо Debian колись розділить і його, симптом буде │
# │ такий самий підлий, тож хай перевірка ловить обидва випадки.      │
# └───────────────────────────────────────────────────────────────────┘
for m in IO::Multiplex Net::Server::Multiplex; do
    perl -M"$m" -e1 2>/dev/null && continue
    pkg=libio-multiplex-perl
    [ "$m" = Net::Server::Multiplex ] && pkg=libnet-server-perl
    die "немає Perl-модуля $m, на якому тримається postgrey.
Додати $pkg в _images/postgrey/Dockerfile і перезібрати: ./mailctl build"
done

# ── Власні whitelist-и ───────────────────────────────────────────────
# Пакетні whitelist_clients / whitelist_recipients НЕ чіпаємо: на
# джерелах вони застрягли на версії 2015 року, і історія там глибша,
# ніж варта переносу (TODO п.5b). Свої додавання йдуть у *.local, і це
# не наша вигадка, а пакетна конвенція — `postgrey --help` на цьому
# образі: «per default /etc/postgrey/whitelist_clients.local and
# /etc/postgrey/whitelist_recipients.local are also read».
#
# Відсутність *.local — нормальний стан: у самому скрипті стоїть
# `warn ... unless $f =~ /\.local$/`, тобто брак файлу свідомо не є
# помилкою.
for f in whitelist_clients.local whitelist_recipients.local; do
    src=
    if   [ -f "$CUSTOM/$f" ]; then
        src=$CUSTOM/$f
        say "$f — версія ГРУПИ (перекриває спільну)"
    elif [ -f "$SHARED/$f" ]; then
        src=$SHARED/$f
    fi
    [ -n "$src" ] || continue
    install -m 0644 "$src" "/etc/postgrey/$f"
    n=$(grep -cvE '^[[:space:]]*#|^[[:space:]]*$' "/etc/postgrey/$f" || true)
    say "$f: власних записів — $n"
done

# ── Каталог стану ────────────────────────────────────────────────────
# Том змонтований сюди, і власник у нього з хоста. Якщо postgrey не
# може писати, він не ЗБОЇТЬ — він просто не запам'ятає жодної трійки,
# тобто кожен лист затримуватиметься заново, вічно. Рівно той клас тихої
# помилки, на якому ми стояли з правами 0600 на mysql-init.
#
# У образі є користувач postgrey (uid 100), і `--user` має дефолтом саме
# його — тобто демон скине привілеї сам, незалежно від того, від кого
# стартував entrypoint.
install -d -o postgrey -g postgrey -m 0700 "$DBDIR"
su -s /bin/sh -c "test -w '$DBDIR'" postgrey \
    || die "postgrey не може писати в $DBDIR. Без цього грейлист не
зберігається й кожен лист затримувався б заново — тому не запускаємось."

# ── Затримка й термін життя записів ──────────────────────────────────
# ┌───────────────────────────────────────────────────────────────────┐
# │ 20 с і 60 діб — НЕ пакетні дефолти (ті 300 с і 35 діб), а явний   │
# │ вибір, узятий не з голови: рівно ці значення стояли й на office,  │
# │ і на isp. Два незалежні сервери — це вже не смак одного         │
# │ адміна, а усталена практика.                                      │
# │                                                                   │
# │ Різниця відчутна: при 300 с легальний відправник, який повторює   │
# │ раз на 10 хвилин, доставить лист через 10 хвилин замість 20 с.    │
# │ Рішення №21 (на isp-подібній групі нічого не ламати) саме про   │
# │ це — 312 абонентів ніколи не мали greylisting-у взагалі.          │
# │                                                                   │
# │ Параметри ГРУПИ, а не константи, бо рішення №21 прямо передбачає  │
# │ підкручування ПІСЛЯ статистики.                                   │
# └───────────────────────────────────────────────────────────────────┘
DELAY=${GREYLIST_DELAY:-20}
MAX_AGE=${GREYLIST_MAX_AGE:-60}

case "${1:-}" in
    '')      ;;
    check)
        say "режим check: версія, параметри й ефективні whitelist-и"
        postgrey --version 2>&1 || true
        echo
        echo "── /etc/postgrey ──"
        ls -l /etc/postgrey/
        for f in /etc/postgrey/*.local; do
            [ -f "$f" ] || continue
            echo
            echo "── $f ──"
            cat "$f"
        done
        exit 0
        ;;
    *)  die "невідомий аргумент '$1'; умію лише 'check'" ;;
esac

# ── Запуск ───────────────────────────────────────────────────────────
# --inet з ЯВНОЮ адресою, і це не стиль: `postgrey --help` каже
# «listen on PORT, localhost if HOST is not specified». Postfix у
# СУСІДНЬОМУ контейнері, тож дефолт означав би, що нас ніхто не питає, і
# greylisting мовчки не діє.
#
# 0.0.0.0, а не ${INTERNAL_PREFIX}.32 — щоб не тримати другу копію
# власної адреси поруч із шаблоном compose. ACL у postgrey немає
# (на відміну від spamd, рішення №34), тобто будь-хто в internal-мережі
# групи може запитати політику. Приймається: та сама межа довіри, що й у
# мілтерів opendkim/opendmarc, які теж слухають усю мережу групи.
#
# Дефолти, які лишаємо свідомо (всі з --help цього образу):
#   --lookup-by-subnet увімкнений, IPv4 ріжеться до /24. Тобто ключем є
#     ПІДМЕРЕЖА, а не адреса — правильно для великих відправників, що
#     повторюють з іншого вузла пулу, інакше кожна спроба виглядала б
#     новою;
#   --auto-whitelist-clients=5 — після п'яти успішних доставок клієнт
#     перестає затримуватись узагалі;
#   --greylist-action=DEFER_IF_PERMIT — відкладаємо лише те, що решта
#     обмежень пропустила б;
#   --retry-window=2 — на першу повторну спробу дається дві доби.
say "запускаю postgrey (затримка ${DELAY} с, термін записів ${MAX_AGE} діб)"
postgrey \
    --inet=0.0.0.0:$PORT \
    --dbdir="$DBDIR" \
    --delay="$DELAY" \
    --max-age="$MAX_AGE" &
PG_PID=$!

# ── Чи справді слухає ────────────────────────────────────────────────
# Фон у postgrey опційний (`-d, --daemonize`), тобто класу `-f` із
# spamass-milter тут немає. Проба лишається сторожем на два випадки:
# процес помер при старті, і хтось колись додав -d.
#
# Чому це важливіше, ніж для мілтера: Postfix із `check_policy_service`
# на мертвий сервіс відповідає 451 на ВСЮ пошту. Тобто збій цього
# контейнера — не «фільтр не працює», а «пошта не приймається».
i=0
while ! (exec 3<>/dev/tcp/127.0.0.1/$PORT) 2>/dev/null; do
    if ! kill -0 "$PG_PID" 2>/dev/null; then
        wait "$PG_PID" 2>/dev/null || code=$?
        die "postgrey завершився (код ${code:-0}), $PORT не слухає.
Причина в рядках вище."
    fi
    i=$((i + 1))
    [ "$i" -lt 30 ] || break
    sleep 1
done

if ! kill -0 "$PG_PID" 2>/dev/null; then
    die "postgrey ВІДГАЛУЗИВСЯ: $PORT слухає, але запущений нами процес
уже вийшов. Отже десь з'явився -d/--daemonize — прибрати, інакше
наглядач за демоном не стежить."
fi

[ "$i" -lt 30 ] || say "УВАГА — postgrey живий, але за 30 с не почав слухати $PORT"

say "postgrey слухає $PORT"

# ┌───────────────────────────────────────────────────────────────────┐
# │ TERM МУСИТЬ ДОЇХАТИ ДО ДЕМОНА, а не лишитись у цьому шеллі.       │
# │                                                                   │
# │ Без trap-а `docker stop` вбиває shell, postgrey сигналу не бачить,│
# │ і через grace-період (типово 10 с) прилітає SIGKILL. Два          │
# │ наслідки, і другий неприємніший:                                  │
# │   - кожен `mailctl reload` довший на ці 10 секунд;                 │
# │   - база грейлиста (DB_File) закривається НЕ чисто. Пошкоджений   │
# │     файл означає, що postgrey або не стартує, або почне з         │
# │     порожнього стану — тобто кожен відправник затримається наново.│
# │                                                                   │
# │ Та сама конструкція, що в spamassassin і clamav.                  │
# └───────────────────────────────────────────────────────────────────┘
trap 'kill "$PG_PID" 2>/dev/null || true' TERM INT

wait "$PG_PID"
code=$?
say "postgrey завершився (код $code) — зупиняю контейнер"
exit 1
