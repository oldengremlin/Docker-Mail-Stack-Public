#!/usr/bin/env bash
# Білдить і тегує спільні образи. Виконати один раз (і потім при апдейтах пакетів).
# Усі групи юзають ОДНІ Й ТІ Ж теговані образи через image: у своєму
# docker-compose — не білдиться N разів на кожну групу.
#
# Тег фіксований і НЕ береться з аргументу командного рядка навмисно:
# раніше тут був $1, що міняв ЛИШЕ вихідний тег, а не FROM у Dockerfile —
# це давало можливість отримати образ, потегований чужою назвою реалізу,
# який насправді зібраний з іншої бази. Якщо колись реально знадобиться
# паралельно тримати збірки під різні релізи Debian — тоді робимо це через
# ARG DEBIAN_TAG у Dockerfile і --build-arg тут, з тегом виведеним з ТОГО Ж
# значення.
#
# База — debian:trixie-slim (поточний stable). Dovecot тут 2.4.x зі зміненим
# синтаксисом dovecot.conf проти bookworm-івського 2.3.x — свідомо йдемо на
# переписування конфігів під нову версію, натомість лишаємось на актуальному
# релізі Debian. Користувачів/поштові скриньки це не стосується, переносяться
# як є незалежно від версії Dovecot.
set -euo pipefail
cd "$(dirname "$0")"

TAG="trixie"

# ── Сторож: бектики в неквотованому heredoc ───────────────────────────
# Це ЧЕТВЕРТИЙ випадок одного класу в проєкті, і третій — уже після
# того, як правило було записане в PITFALLS разом із командою для
# перевірки. Отже тексту замало: перевірка мусить бути в коді.
#
# У `cat > файл <<EOF` (розділювач БЕЗ лапок) shell підставляє змінні —
# і разом із ними виконує `...` та $(...). Рядок, що ВИГЛЯДАЄ
# коментарем, для shell просто текст heredoc, тобто коментарем не є.
# Помилка ще й частково тиха: конфіг складається, просто з дірками на
# місці кожного бектикованого слова.
#
# ${...} не чіпаємо — заради нього heredoc і лишається неквотованим.
# Де підстановка не потрібна, правильна відповідь — <<'EOF'.
hd_guard() {
    awk '
        # Початок heredoc. Квотований розділювач (<<"X" або <<'"'"'X'"'"')
        # безпечний — там shell не підставляє нічого.
        !inside && match($0, /<<-?[A-Za-z_][A-Za-z0-9_]*/) {
            inside = 1
            delim  = substr($0, RSTART, RLENGTH)
            sub(/^<<-?/, "", delim)
            next
        }
        inside && $0 == delim { inside = 0; next }
        inside && (/`/ || /\$\(/) {
            printf "%s:%d: бектик або $( у неквотованому heredoc <<%s: %s\n", \
                   FILENAME, FNR, delim, $0
            bad = 1
        }
        END { exit bad ? 1 : 0 }
    ' "$@"
}
if ! hd_guard */entrypoint.sh; then
    echo "" >&2
    echo "Збірку спинено: рядки вище виконаються як команди при старті" >&2
    echo "контейнера, а згенерований конфіг складеться з дірками." >&2
    echo "Лікування: «лапки» замість бектиків, або <<'"'"'EOF'"'"' там," >&2
    echo "де підстановка змінних не потрібна." >&2
    exit 1
fi

# Контроль самого сторожа: на завідомо зіпсованому вході він МУСИТЬ
# спрацювати. Без цього зміна формату чи помилка в awk зробила б
# перевірку тихо завжди-успішною — рівно те, від чого вона захищає.
probe=$(mktemp -d)
trap 'rm -rf "$probe"' EXIT
mkdir -p "$probe/x"
printf 'cat > /tmp/f <<CONF\n# %s\nCONF\n' '`echo hi`' > "$probe/x/entrypoint.sh"
if (cd "$probe" && hd_guard */entrypoint.sh) >/dev/null 2>&1; then
    echo "сторож heredoc не спрацював на підробленому вході — він зламаний" >&2
    exit 1
fi
rm -rf "$probe"; trap - EXIT

for svc in postfix dovecot postgrey opendkim opendmarc spamassassin clamav certbot; do
    echo "==> building mail/${svc}:${TAG}"
    docker build -t "mail/${svc}:${TAG}" "./${svc}"
done

# Roundcube — окремо, і НЕ в циклі вище, бо його база не debian:trixie.
# Це офіційний образ Roundcube з доданим плагіном sauserprefs
# (див. roundcube/Dockerfile), тож тег ":trixie" на ньому був би
# брехнею — рівно тією, через яку в цьому проєкті вже був образ,
# потегований одним релізом і зібраний з іншого.
#
# Тег ВИВОДИТЬСЯ з FROM у самому Dockerfile, а не задається тут: дві
# змінні, що мусять узгоджуватись, розійшлися б мовчки при першій же
# зміні версії.
RC_BASE=$(sed -n 's|^FROM  *roundcube/roundcubemail:\([^ ]*\).*|\1|p' roundcube/Dockerfile)
[ -n "$RC_BASE" ] || { echo "не вийшло прочитати FROM з roundcube/Dockerfile" >&2; exit 1; }
# Відкидаємо суфікс варіанта (-apache): у тезі образу він зайвий, а от
# у FROM обов'язковий.
RC_TAG="${RC_BASE%-apache}"
echo "==> building mail/roundcube:${RC_TAG} (база roundcube/roundcubemail:${RC_BASE})"
docker build -t "mail/roundcube:${RC_TAG}" ./roundcube

echo "Готово. Образи:"
docker images 'mail/*'
