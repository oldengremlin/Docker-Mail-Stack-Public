<?php
// ─────────────────────────────────────────────────────────────────────
//  Roundcube: спільний конфіг для всіх груп.
//
//  Монтується в /var/roundcube/config (НЕ в підкаталог!). Офіційний
//  образ читає цей каталог так:
//      for fn in `ls /var/roundcube/config/*.php`; do
//          echo "include('$fn');" >> config/config.docker.inc.php
//      done
//  Тобто БЕЗ рекурсії — файл у підкаталозі не читається МОВЧКИ. Саме
//  на цьому й спіймались: монтування стояло на config/custom.
//
//  include дописується В КІНЕЦЬ config.docker.inc.php, а той
//  включається в кінці config.inc.php. Отже цей файл іде ПОСЛІДНІМ і
//  перебиває і дефолти, і те, що образ згенерував з env. Значення,
//  які образ ставить сам (db_dsnw, imap_host, smtp_host, skin,
//  plugins, temp_dir), тут СВІДОМО не дублюються — інакше два джерела
//  одного параметра розійшлися б мовчки.
//
//  Секретів тут немає й бути не може: файл комітиться в git. Усе
//  секретне приходить через env (див. _template/docker-compose.yml) і
//  читається тут через getenv().
// ─────────────────────────────────────────────────────────────────────

// ── За зворотним проксі ──────────────────────────────────────────────
// nginx з _proxy/ термінує TLS і ходить сюди по HTTP. Без use_https
// Roundcube генерував би http:// посилання на https:// сторінці.
$config['use_https'] = true;

// Довіряти X-Forwarded-* і X-Real-IP ЛИШЕ від адреси проксі. Без
// цього в логах Roundcube стоятиме IP проксі замість клієнтського, а
// з довірою до будь-кого — підробний IP від самого клієнта.
// Адреса статична за побудовою: mailctl proxy attach дає nginx
// рівно <INTERNAL_PREFIX>.100 у мережі кожної групи.
$config['proxy_whitelist'] = [getenv('PROXY_IP')];

// Host: підробляється клієнтом, а Roundcube будує з нього посилання
// (включно зі сторінкою логіна). Порожній список приймає будь-який
// хост, тому список тут — не косметика.
$config['trusted_host_patterns'] = [
    '^' . preg_quote((string) getenv('WEBMAIL_FQDN'), '/') . '$',
];

// ── З'єднання з Dovecot і Postfix ────────────────────────────────────
// imap_host / smtp_host задає образ з env (ROUNDCUBEMAIL_DEFAULT_HOST,
// ROUNDCUBEMAIL_SMTP_SERVER) — там стоїть tls://<MAIL_HOSTNAME>.
// TLS обов'язковий, і не для галочки: у Dovecot
// auth_allow_cleartext = no (рішення №14), тобто PLAIN/LOGIN поза TLS
// просто не приймаються. Голий dovecot:143 тут не автентикувався б.
//
// smtp_user/smtp_pass не задаємо: дефолт і так '%u'/'%p', тобто
// відправка йде АВТЕНТИФІКОВАНОЮ. Це важливо — у small MYNETWORKS
// порожній (рішення №30), і неавтентикований Roundcube отримав би
// "Relay access denied".
//
// ┌───────────────────────────────────────────────────────────────────┐
// │ Перевірки сертифіката тут НЕМАЄ жодного рядка — і це навмисно.    │
// │                                                                   │
// │ Раніше стояв `verify_peer => false`, бо на MAIL_HOSTNAME лежала   │
// │ самопідписана заглушка. Відколи `mailctl certs <група>` видає     │
// │ справжній сертифікат (CN = MAIL_HOSTNAME, те саме ім'я, за яким   │
// │ Roundcube сюди й ходить), перевірка працює дефолтом PHP, і        │
// │ вимикати її більше нема причини.                                  │
// │                                                                   │
// │ Власних `*_conn_options` не задаємо навіть із `verify_peer =>     │
// │ true`: це був би третій список опцій, який мусить узгоджуватись   │
// │ із дефолтом PHP і з конфігом Dovecot, і розійшовся б мовчки.      │
// │                                                                   │
// │ НАСЛІДОК, ЯКИЙ ТРЕБА ЗНАТИ: якщо сертифікат протермінується,      │
// │ стане самопідписаним знову (`certs` не спрацював, а заглушка      │
// │ лишилась) або MAIL_HOSTNAME перестане збігатися з CN — вебмейл    │
// │ просто не з'єднається з IMAP. Симптом буде «не вдалося            │
// │ підключитись до сервера», а причина — у сертифікаті.              │
// └───────────────────────────────────────────────────────────────────┘

// ── Сесії ────────────────────────────────────────────────────────────
// Дефолт — 10 хвилин, і для вебмейлу це мало: користувач пише лист
// довше, ніж читає. session_storage у дефолтах уже 'db', тобто сесії
// переживають перестворення контейнера — але лише разом із фіксованим
// des_key (див. ROUNDCUBE_DES_KEY у шаблоні).
$config['session_lifetime'] = 60;

// ── Плагін password: ручна операція №3 з мети проєкту ────────────────
// Сенс у тому, щоб користувач міняв пароль САМ. Поки це робить адмін
// через `mailctl user passwd`, операція не зникла — лише переїхала.
$config['password_driver'] = 'sql';

// hash-argon2id — це PHP password_hash(PASSWORD_ARGON2ID). Dovecot
// читає параметри (m/t/p) із самого хеша, тому значення сходяться без
// узгодження констант. Через 'dovecot' робити НЕ можемо: той драйвер
// викликає doveadm pw, а доводити doveadm у контейнер вебмейлу — це
// друга інсталяція Dovecot заради однієї команди.
$config['password_algorithm']        = 'hash-argon2id';
// Явний префікс схеми — рішення №25: зміст пароля має визначатись
// самими даними, а не рядком у конфізі Dovecot.
$config['password_algorithm_prefix'] = '{ARGON2ID}';

// Окремий DSN, НЕ основний db_dsnw: у нього інший користувач БД, і
// весь сенс у його правах (див. 60-roundcube.sql). Основний
// користувач вебмейлу до поштової бази доступу не має взагалі.
$config['password_db_dsn'] = getenv('ROUNDCUBE_PASSWD_DSN');

// Ріжемо адресу в SQL, а не плейсхолдерами плагіна. Причина
// практична: %u гарантовано є (README плагіна), а чим саме плагін
// віддає домен — %d чи %h — з його ж прикладів читається
// суперечливо, і помилка тут МОВЧКИ оновила б пароль не тому
// користувачеві. CONCAT індексу не використає, але зміна пароля —
// операція рідка.
//
// Бонус, не випадковий: WHERE читає рівно `user` і `domain`, тобто ті
// самі стовпці, на які виданий SELECT. Права й запит збігаються за
// побудовою, і SELECT на `passwd` не потрібен — хеші цей користувач
// прочитати не може.
//
// КЛЮЧІВ ДВА, і це не перестраховка. `%u` — логін ЯК ЙОГО НАБРАЛИ, а
// рішення №15 дозволяє заходити і коротким логіном, і повною адресою.
// З одним лише CONCAT на isp і office запит не збігався б НІКОЛИ
// (логін там не пов'язаний з адресою у 240 випадках із 312), тобто
// зміна власного пароля з вебмейлу мовчки не працювала б — а це
// ручна операція №3 з мети проєкту. `login` може бути NULL (групи
// small-типу), і NULL=%u дає false, тож зайвих збігів не виникає.
$config['password_query'] =
    "UPDATE users SET passwd=%P"
    . " WHERE (login=%u OR CONCAT(user,'@',domain)=%u) LIMIT 1";

// Старий пароль запитуємо (дефолт dist, але явно: ціна помилки тут —
// зміна пароля з чужої незакритої сесії).
$config['password_confirm_current'] = true;
$config['password_minimum_length']  = 8;
// Дозволяє перезаписати пароль тим самим значенням. Потрібно саме
// нам: рішення №25 лишає частину перенесених паролів у старих схемах,
// і це єдиний спосіб перехешувати їх без зміни самого пароля.
$config['password_force_save'] = true;

// ── mailstack_identity: адреса першої ідентичності ───────────────────
// Наш власний плагін (_images/roundcube/mailstack_identity/). Без цих
// двох значень він не робить нічого, тому вони тут, а не в коді:
// запит залежить від СХЕМИ групи, а не від плагіна.
//
// DSN той самий, що в плагіна password, і це свідомо: обидва читають
// рівно `user`, `domain` і `login`, обидва НЕ мають SELECT на
// `passwd`. Четвертий користувач БД додав би права, не додавши
// розділення — сенс рішення №35 у правах, не в кількості імен.
$config['mailstack_identity_dsn'] = getenv('ROUNDCUBE_PASSWD_DSN');

// Ті самі два ключі, що в password_query, і з тієї ж причини.
// Плейсхолдери тут `?` (а не %u): запит іде через rcube_db::query з
// прив'язкою параметрів, тобто лапки в логіні нешкідливі.
$config['mailstack_identity_query'] =
    "SELECT CONCAT(`user`, '@', `domain`)"
    . " FROM `users`"
    . " WHERE `login` = ? OR CONCAT(`user`, '@', `domain`) = ?";

// ── markasjunk: кнопка «спам» ────────────────────────────────────────
// ┌───────────────────────────────────────────────────────────────────┐
// │ move_spam / move_ham = true ОБОВ'ЯЗКОВІ, інакше навчання не       │
// │ відбувається МОВЧКИ.                                              │
// │                                                                   │
// │ Дефолт плагіна — false: він лише ставить keyword Junk, не         │
// │ переносячи лист. А наше донавчання (рішення №34) чіпляється до    │
// │ IMAP-події з `cause = copy`, тобто до COPY/MOVE. Флаг такої       │
// │ події не створює → spamc не викликається → bayes не вчиться, і    │
// │ при цьому в інтерфейсі все виглядає як спрацювало.                │
// │                                                                   │
// │ Альтернатива — додати `cause = flag` у dovecot.conf. Відкинута:   │
// │ тоді навчання запускав би і будь-який клієнт, що просто ставить   │
// │ мітку, не переносячи лист, а перенос — це те, що користувач       │
// │ справді робить свідомо.                                           │
// │                                                                   │
// │ learning_driver лишається null СВІДОМО: учить не плагін, а        │
// │ imapsieve на боці Dovecot. Тобто перетягування листа мишкою й     │
// │ кнопка дають РІВНО один і той самий шлях.                         │
// └───────────────────────────────────────────────────────────────────┘
$config['markasjunk_move_spam'] = true;
$config['markasjunk_move_ham']  = true;

// ── sauserprefs: власні правила SpamAssassin ─────────────────────────
// Плагін пише в таблицю `userpref` бази СТАНУ SpamAssassin (рішення
// №33), окремим користувачем БД з правами рівно на неї — ні до bayes_*,
// ні до поштових таблиць доступу немає.
//
// ┌───────────────────────────────────────────────────────────────────┐
// │ ТУТ ЗАДАНО ВСЕ ЯВНО, і це не надмірність.                         │
// │                                                                   │
// │ Дефолти плагіна живуть у `plugins/sauserprefs/config.inc.php`,    │
// │ який кладе composer-івський plugin-installer. Ми плагін КОПІЮЄМО  │
// │ (див. _images/roundcube/Dockerfile) і того файлу не створюємо —   │
// │ отже дефолтів НЕМАЄ ЖОДНИХ.                                       │
// │                                                                   │
// │ Коштувало це так: незадані імена таблиці й стовпців пішли в SQL   │
// │ порожніми рядками, і запит вийшов                                 │
// │     SELECT `, ` FROM ` WHERE ` = '…'                              │
// │ тобто синтаксична помилка MariaDB, яку вебмейл показав як         │
// │ «Неможливо підключитися до бази даних» — повідомлення, що вказує  │
// │ зовсім не туди.                                                   │
// │                                                                   │
// │ Класти `config.inc.php` в каталог плагіна — НЕ вихід: Roundcube   │
// │ зливає його ПОВЕРХ основного, тобто приклад                       │
// │ `mysql://username:password@localhost/database` з .dist перекрив   │
// │ би наш справжній DSN.                                             │
// └───────────────────────────────────────────────────────────────────┘
$config['sauserprefs_db_dsnw'] = getenv('ROUNDCUBE_PREFS_DSN');

// Схема таблиці — пакетна, SpamAssassin-івська (`mailctl db-schema`
// дістає її З ОБРАЗУ). Значення тут збігаються з нею; якщо апстрім
// колись змінить схему, зламається саме тут і гучно.
$config['sauserprefs_sql_table_name']       = 'userpref';
$config['sauserprefs_sql_username_field']   = 'username';
$config['sauserprefs_sql_preference_field'] = 'preference';
$config['sauserprefs_sql_value_field']      = 'value';

// Ключ глобальних правил. ОДИНАРНІ лапки обов'язкові: у подвійних PHP
// спробував би розкрити $GLOBAL як змінну. У `.dist` плагіна тут
// стоїть `'\$GLOBAL'` — зайвий бекслеш, який у нашому випадку доїхав
// у SQL буквально (`WHERE … = '\\$GLOBAL'`).
$config['sauserprefs_global_userid'] = '$GLOBAL';

// SpamAssassin 4: нові імена директив (welcomelist/blocklist замість
// whitelist/blacklist). Без цього плагін писав би старі, а наш
// SpamAssassin 4 їх уже не розуміє.
$config['sauserprefs_sav4'] = true;

// ┌───────────────────────────────────────────────────────────────────┐
// │ КЛЮЧ КОРИСТУВАЧА — дефолтний `%u` (логін сесії), і це свідомо.    │
// │                                                                   │
// │ Він МУСИТЬ збігатися з тим, що spamass-milter передає у spamc     │
// │ через -u/-e, а там повна адреса (рішення №31). У групах           │
// │ small-типу логін і є повна адреса, тож %u підходить точно.        │
// │                                                                   │
// │ `%i` (email з дефолтної identity) НЕ БРАТИ, хоч він виглядає      │
// │ доречнішим: identity користувач редагує сам, тобто міг би         │
// │ підставити ЧУЖУ адресу й писати правила за неї. %u — логін        │
// │ сесії, підробити його не можна.                                   │
// │                                                                   │
// │ Для групи з КОРОТКИМ логіном (office, isp — рішення №15) %u не  │
// │ збіжиться з ключем мілтера, і правила просто не застосуються —    │
// │ мовчки. Це треба вирішувати разом зі зведенням схем, а не         │
// │ підстановкою %i.                                                  │
// └───────────────────────────────────────────────────────────────────┘
$config['sauserprefs_userid'] = '%u';

// ┌───────────────────────────────────────────────────────────────────┐
// │ ЩО КОРИСТУВАЧЕВІ НЕ МОЖНА ПЕРЕВИЗНАЧАТИ.                          │
// │ Це не косметика: дефолти самого плагіна суперечать трьом нашим    │
// │ рішенням, і без цього списку кнопка в вебмейлі тихо ламала б їх.  │
// └───────────────────────────────────────────────────────────────────┘
$config['sauserprefs_dont_override'] = [
    // Рішення №31: SpamAssassin працює МІЛТЕРОМ, а мілтер змінює
    // заголовки, не тіло. report_safe = 1 (дефолт плагіна!) просить
    // загорнути лист у MIME-вкладення — чого spamass-milter не вміє.
    'report_safe',

    // ┌───────────────────────────────────────────────────────────┐
    // │ САМ `bayes_auto_learn` тут НЕ заборонений, а його ПОРОГИ — │
    // │ заборонені. Різниця не формальна.                          │
    // │                                                            │
    // │ Увімкнути чи вимкнути автонавчання — справа користувача:   │
    // │ bayes у нас per-user, він псує або наповнює рівно свою     │
    // │ базу. А ось пороги вирішують, НА ЧОМУ воно вчиться.        │
    // │                                                            │
    // │ Безпечним autolearn робить саме те, що він чіпає лише      │
    // │ листи ДАЛЕКО за межами порога: нижче 0.1 і вище 12 при     │
    // │ `required_score` 5 (так у нашому local.cf). Поставивши     │
    // │ Junk threshold = 1, користувач отримує навчання на всьому, │
    // │ що набрало хоч бал, — тобто фільтр учиться на сумнівному   │
    // │ й сам себе переконує. Це рівно той механізм, який рішення  │
    // │ №34 прибрало з office, лише зібраний руками через UI.      │
    // │                                                            │
    // │ Перевірено на полігоні: форма зберегла                     │
    // │ `bayes_auto_learn_threshold_spam = 1` без жодного           │
    // │ попередження.                                              │
    // └───────────────────────────────────────────────────────────┘
    'bayes_auto_learn_threshold_nonspam',
    'bayes_auto_learn_threshold_spam',

    // Параметр ГРУПИ (SA_DNSBL у group.env): у власника є свої
    // рекурсивні резолвери, і чи мають DNSBL сенс — вирішується на
    // рівні групи, а не кожним користувачем окремо.
    'skip_rbl_checks',

    // Рішення №33: AWL не вмикаємо (у SpamAssassin 4 плагін навіть не
